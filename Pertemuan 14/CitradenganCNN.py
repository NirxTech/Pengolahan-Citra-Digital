# 4. TRANSFER LEARNING (VGG16)
# ==========================================
def build_transfer_learning_model():
    inputs = layers.Input(shape=(32, 32, 3))
    x = layers.Resizing(96, 96)(inputs)
    x = applications.vgg16.preprocess_input(x * 255.0)

    # Base model - Feature Extraction
    base_model = applications.VGG16(weights='imagenet', include_top=False, input_shape=(96, 96, 3))
    base_model.trainable = False

    x = base_model(x, training=False)
    x = layers.GlobalAveragePooling2D()(x)
    x = layers.Dense(256, activation='relu')(x)
    x = layers.Dropout(0.5)(x)
    outputs = layers.Dense(num_classes, activation='softmax')(x)

    model = models.Model(inputs, outputs, name='Transfer_Learning_VGG16')
    model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
    return model, base_model

print("\nTraining Transfer Learning (Feature Extraction)...")
model_tl, base_model_tl = build_transfer_learning_model()
start_time = time.time()

history_tl = model_tl.fit(
    datagen.flow(X_train, y_train_cat, batch_size=64),
    validation_data=(X_val, y_val_cat),
    steps_per_epoch=len(X_train) // 64,
    epochs=10,
    verbose=1
)

# FINE TUNING
print("\nMelakukan Fine-Tuning pada Transfer Learning...")
base_model_tl.trainable = True
# Unfreeze 4 layer terakhir dari VGG16
for layer in base_model_tl.layers[:-4]:
    layer.trainable = False

model_tl.compile(optimizer=tf.keras.optimizers.Adam(1e-5), loss='categorical_crossentropy', metrics=['accuracy'])
history_fine = model_tl.fit(
    datagen.flow(X_train, y_train_cat, batch_size=64),
    validation_data=(X_val, y_val_cat),
    epochs=5,
    verbose=1
)
