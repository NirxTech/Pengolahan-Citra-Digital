def generate_comparison_table(hist_scratch, hist_tl, time_scratch, time_tl):
    acc_scratch = hist_scratch.history['accuracy'][-1]
    val_acc_scratch = hist_scratch.history['val_accuracy'][-1]
    loss_scratch = hist_scratch.history['loss'][-1]
    val_loss_scratch = hist_scratch.history['val_loss'][-1]

    acc_tl = hist_tl.history['accuracy'][-1]
    val_acc_tl = hist_tl.history['val_accuracy'][-1]
    loss_tl = hist_tl.history['loss'][-1]
    val_loss_tl = hist_tl.history['val_loss'][-1]

    data = {
        'Model': ['CNN Scratch (Adam)', 'Transfer Learning VGG16'],
        'Train Acc': [f"{acc_scratch:.4f}", f"{acc_tl:.4f}"],
        'Val Acc': [f"{val_acc_scratch:.4f}", f"{val_acc_tl:.4f}"],
        'Train Loss': [f"{loss_scratch:.4f}", f"{loss_tl:.4f}"],
        'Val Loss': [f"{val_loss_scratch:.4f}", f"{val_loss_tl:.4f}"],
        'Waktu (Menit)': [f"{time_scratch/60:.2f}", f"{time_tl/60:.2f}"]
    }

    df = pd.DataFrame(data)

    print("\n" + "="*80)
    print("TABEL PERBANDINGAN PERFORMA EKSPERIMEN (EPOCH TERAKHIR)")
    print("="*80)
    print(df.to_string(index=False, justify='center'))
    print("="*80 + "\n")

