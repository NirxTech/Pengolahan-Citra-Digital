# 3. CNN DARI AWAL (Functional API)
# ==========================================
def build_cnn_scratch(optimizer='adam', learning_rate=0.001):
    inputs = layers.Input(shape=(32, 32, 3), name='input_layer')

    x = layers.Conv2D(32, (3,3), activation='relu', name='conv2d_1')(inputs)
    x = layers.MaxPooling2D(2,2, name='pool_1')(x)
    x = layers.Conv2D(64, (3,3), activation='relu', name='conv2d_2')(x)
    x = layers.MaxPooling2D(2,2, name='pool_2')(x)
    x = layers.Conv2D(128, (3,3), activation='relu', name='conv2d_3')(x)

    x = layers.Flatten(name='flatten')(x)
    x = layers.Dense(256, activation='relu', name='dense_1')(x)
    x = layers.Dropout(0.5, name='dropout')(x)
    outputs = layers.Dense(num_classes, activation='softmax', name='output_layer')(x)

    model = models.Model(inputs=inputs, outputs=outputs, name='CNN_Scratch')

    if optimizer == 'adam':
        opt = tf.keras.optimizers.Adam(learning_rate=learning_rate)
    else:
        opt = tf.keras.optimizers.SGD(learning_rate=learning_rate, momentum=0.9)

    model.compile(optimizer=opt, loss='categorical_crossentropy', metrics=['accuracy'])
    return model

print("\nTraining CNN dari Awal (Scratch) dengan Adam Optimizer...")
model_scratch = build_cnn_scratch(optimizer='adam')
start_time = time.time()

history_scratch = model_scratch.fit(
    datagen.flow(X_train, y_train_cat, batch_size=64),
    validation_data=(X_val, y_val_cat),
    steps_per_epoch=len(X_train) // 64,
    epochs=15,
    verbose=1
)
scratch_time = time.time() - start_time


